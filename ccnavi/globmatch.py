r"""glob を正規表現に直す。意味は標準ライブラリの `fnmatch` そのまま。

## 自前の記法をやめた

以前はここに自前の翻訳があった。`*` と `?` と空白の並びを扱い、語の切れ目を
自動で挟み、パスの区切りを両方の綴りに当てていた。便利だったが、書いたものと
当たるものの間に見えない層が 1 枚あることになり、その層が実際に事故を起こした。
語の中に置いたワイルドカードの両隣に切れ目が入り、`foo*bar` が `foobar` に
当たらなくなっていた。書いた人は当たるつもりで、実際は何も止めていない。

いまは `fnmatch.translate` に任せる。`fnmatch` の意味は広く知られていて、
`.claude/settings.json` の `permissions` が使う書き方とも揃う。
このモジュールが足すのは区切り文字の正規化 1 つだけ。

## 文字列全体に当たる

`fnmatch` は文字列全体に当てる。部分一致が欲しければ前後に `*` を自分で書く。

    "*git push*"          コマンドのどこかに git push があれば当たる
    "*/.claude/ccnavi/*"  パスのどこかにその並びがあれば当たる
    "*.pem"               .pem で終わるものに当たる

自動で前後に `*` を足さない。足すと「書いたものがそのまま当たる」が崩れて、
やめたはずの見えない層が戻ってくる。

## 語の切れ目は自動で入れない

`*sed*` は `sedate` にも当たる。切れ目が要るなら、右側は空白を書いて
`*sed *` とする。左側は glob では書けない。`*git push*` は `legit push` にも
当たり、`* git push*` と書くと今度は行頭の `git push` が外れる。
左の切れ目が要るルールは `regex` を使う。

## 区切り文字だけは正規化する

ルールは 1 回書いて、どの機械でも同じ意味でなければならない。`/` と書いたら
`\` にも当てる。ここだけは `fnmatch` の外で足している。

翻訳したあとの式に現れる `/` を置き換える形にしてある。素の `/` が式に入るのは
glob に `/` を書いたときだけなので、置き換え先を取り違えることはない。
例外は文字クラスの中に `/` を書いた `[a/b]` のような形で、これは組み立てに
失敗して読み込み時に名指しで落ちる。黙って別の意味になるより、落ちるほうがよい。
"""

from __future__ import annotations

import fnmatch

# パスの区切り。`/` と書いたら `\` にも当てる。
_SEPARATOR = r"[\\/]"


def translate(glob: str) -> str:
    """glob を正規表現にする。文字列全体に当たる形で返す。"""
    return fnmatch.translate(glob).replace("/", _SEPARATOR)

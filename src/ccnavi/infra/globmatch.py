r"""glob を正規表現に直す。意味は標準ライブラリの `fnmatch` そのまま。

## 自前の記法を持たない

翻訳は `fnmatch.translate` に任せる。`fnmatch` の意味は広く知られていて、
`.claude/settings.json` の `permissions` が使う書き方とも揃う。
このモジュールが足すのは区切り文字の正規化 1 つだけ。

語の切れ目を自動で挟むような独自の層を足すと、書いたものとヒットするものの間に
見えない変換が 1 つ挟まる。たとえば語の中に置いたワイルドカードの両隣に切れ目が入ると、
`foo*bar` が `foobar` にヒットしない。書いたユーザはヒットするつもりで、実際は何も止めていない。

## 文字列全体にヒットする

`fnmatch` は文字列全体に適用する。部分一致が欲しければ前後に `*` を自分で書く。

    "*git push*"          コマンドのどこかに git push があればヒットする
    "*/.ccnavi/approved/*" パスのどこかにその文字列があればヒットする
    "*.pem"               .pem で終わるものにヒットする

自動で前後に `*` を足さない。足すと「書いたものがそのままヒットする」が成り立たなくなって、
見えない変換が挟まる。

## 語の切れ目は自動で入れない

`*sed*` は `sedate` にもヒットする。切れ目が要るなら、右側は空白を書いて
`*sed *` とする。左側は glob では書けない。`*git push*` は `legit push` にも
ヒットし、`* git push*` と書くと今度は行頭の `git push` が外れる。
左の切れ目が要るルールは `regex` を使う。

## 区切り文字だけは正規化する

ルールは 1 回書いて、どの機械でも同じ意味でなければならない。`/` と書いたら
`\` にも適用する。ここだけは `fnmatch` の外で足している。

翻訳したあとの式に現れる `/` を置き換える形にしてある。素の `/` が式に入るのは
glob に `/` を書いたときだけなので、置き換え先を取り違えることはない。
例外は文字クラスの中に `/` を書いた `[a/b]` のような形で、これは組み立てに
失敗して読み込み時に名指しで失敗する。気づかないうちに別の意味になるより、失敗するほうがよい。
"""

from __future__ import annotations

import fnmatch

# パスの区切り。`/` と書いたら `\` にも適用する。
_SEPARATOR = r"[\\/]"


def translate(glob: str) -> str:
    """glob を正規表現にする。文字列全体にヒットする形で返す。"""
    return fnmatch.translate(glob).replace("/", _SEPARATOR)

// Package askcontext は、ユーザへの確認（ask）の前に、直前のエージェントの発言が背景と結果を言っているかを調べる。
// 確認の画面に出るのはコマンドや質問だけで、なぜその操作が要るのか、許可と拒否で何が起きるのかは出ないので、確認の前の
// 発言で言わせる。対象は ccnavi が返す確認すべてと AskUserQuestion で、判定（judge）が呼ぶ。
//
// 見るのは会話記録の末尾。最後のユーザの発言（ツールの結果ではない行）より後ろの、サイドチェーンでないアシスタントの
// text を集め、節の見出しがあるかだけを見る（中身が適切かは機械では判断しない）。PreToolUse の時点では直前の発言が
// まだ書かれていないことがある（`claude -p` の実測では 3 回中 2 回が未書き込みで、0.5 秒以内に現れた）。書き込み済みかは、
// この呼び出し自身の tool_use の行があるかで分かる。自分の行がまだ無ければ、見出しが現れるまで AskContextWait まで
// 読み直す。判定できないとき（記録が読めない・パスや tool_use_id が無い・待っても現れない）は通す。促しの検査で、
// 保護ではないので、止めすぎるより通すほうを選ぶ。

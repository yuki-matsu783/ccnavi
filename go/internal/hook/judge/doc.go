// Package judge は実行前チェック（PreToolUse）の判定の本体。ツール呼び出しの引数を見て、通す・聞く・止める・
// 権限モードに渡すを決め、応答（標準出力の JSON）と記録（audit.Record）を同じ結論から作る。
//
// 当てる順は次のとおり。確認の前の発言の検査、組み込みの止め（環境変数の指定・自己防衛のパス・記録の削除・ユーザの判断の経路・
// 子の push・ターン分離のゲート・サブエージェントの禁止・親のワークツリーへの書き込み・レビュー待ち・サブエージェントの起動・
// プロジェクトの食い違い・着手中の子のロック）、書き直しを求める形、ルール（deny・ask・allow）、ワークスペースルート直下への
// シェルの書き込み、チケットの範囲。止める側の結論が出たら、そこで返す。期限（config.HookDeadline）はルールを 1 本当てる
// たびに確かめ、過ぎたらツールの種類で決めた終了コードで終える。照合を打ち切ったルール（pyre.errDepthLimit）は、
// rules が止める側に倒す。
//
// 想定外の失敗（組み込みのルールを組めない・ターン分離のゲートの宣言が不正・応答を書けない）は error で返す。入口は
// 内部エラーの応答にする。panic は受けない。判定の途中で起きる panic は不具合であり、入口がまとめて受ける。

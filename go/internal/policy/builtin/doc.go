// Package builtin は組み込みのルールを持つ。取り返しの付かない操作を止める deny（土台、LoadBase）は、
// 共通レイヤーと config の有無・状態によらず常に効く。共通レイヤーが読めないとき（Load）は、
// 土台に「シェルからガード自身の設定へ書き込む」deny と、Read を通す allow を足した既定だけで判定する。
//
// 既定に入れるのは、止めそこねたときに戻せないものだけ。ガードが機能していない間は、ルールが言及しない
// 呼び出しを権限モードに任せ、ユーザが居るモードなら 1 件ずつ確認させる。Read だけは通す。ワークツリーを
// 変えようがなく、確認が多すぎると見てほしい 1 件が埋もれるため。
//
// 止める形は glob の文字列一致ではなく regex で書く。`git -C . push` や `rm -fr` のような表記違いも止めるため。
// どの式も、照合の時間が入力の長さにほぼ比例するように書く（所有的な繰り返しとアトミックグループを使う）。
// 期限はルールの合間でしか見ないので、1 本の照合が後戻りで長引くと、止められずに通ってしまう。

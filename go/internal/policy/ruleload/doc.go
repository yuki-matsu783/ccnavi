// その上にツリーの設定（ワークスペースの設定とプロジェクトの設定）を足す。足すだけで、後ろの設定が
// 前を上書きしたり取り消したりはしない。判定そのものはここに無い。
//
// パスを持つツールは、共通設定と行き先の 1 つの設定を使う。パスを持たないツールは、共通設定と
// 全設定の和を使う（共通 → 自身 → プロジェクトの名前順）。無い設定は空として扱う。不備ではないので、
// 記録にも lint にも出さない。壊れた設定も空として扱い、記録の fallback に名前を残す。
// 共通設定自身が読めないときだけ、組み込みの既定に戻し、設定は足さない。足すと、何が判定に
// 使われているのかをユーザが読めなくなるため。共通設定も設定のファイルも無ければ、
// 組み込みの既定（Read を通す allow を含む）だけで判定する。

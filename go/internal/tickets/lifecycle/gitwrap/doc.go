// Package gitwrap は、git の入口のラッパー（ccnavi-git.sh）が受けた引数を通すかを決める。
//
// ラッパーは `ccnavi git check <自分の呼び方> <ccnavi-sync.sh の呼び方>` を起こし、git の引数を標準入力に NUL 区切りで
// 渡す（ccnavi の引数として渡すと、`-m` のような語を ccnavi 自身のオプションとして読んでしまうため）。答えは
// `allow`（通す）・`pass`（サブコマンドより前の判定は通った。続きはラッパーが判定する）・`deny <識別子>` と次の行の
// 拒否の文、のどれか。拒否の文の中の呼び方は、ラッパーが渡した `$0` から作るので、どこから打っても合う。
//
// 引数だけで決まる判定を持つ: サブコマンドより前のオプション、どのサブコマンドでも許さない形（設定の一時上書き・
// ファイル書き込みや外部コマンド実行に変えるオプション・判定の起点を動かすオプションと、その略）、読むだけの
// サブコマンド、cat-file・grep・branch・tag・remote・stash・add・commit の形、通さないサブコマンド。
// オプションは許可リストで読む（Walk）。git の parse-options は長いオプションの略を受けるので、一覧にそのままの
// 表記がある名前だけを通し、まとめた短いオプションは 1 字ずつ読む。

// Package shask は、.ccnavi/scripts/ の sh がチケットについて聞くこと（`ccnavi tree <問い> …`）に答える。
// 読むだけで、何も書かない。git はローカルの読み取りだけを使い、ネットワークには出ない。
//
// sh はチケットの YAML も JSON も自分では読まない。答えは 1 行 1 項目（`<キー> <値>`。
// sh は jq を使わない）で返す。頭の行（`tree 1`）が無ければ、sh は「実行ファイルが答えられなかった」と読み、
// 呼ぶ側が決めた答えにする（止める側の検査なら止める側、ツリーを動かす側なら動かさない側）。
// 行・値・終了コードは sh との契約なので変えない。問いは次の 6 つ。
//
//   - `tree parent <ツリー> <名前>`: そのツリーが名前の親のワークツリーかを返す（parent）。加えて、
//     push のゲートが初回の push か、消えた親ブランチの再作成かを見分ける材料（approved・requested・archived・
//     started・mr）を返す。
//   - `tree bound <ツリー> <名前>`: 直接作業のワークツリーがチケットに結び付くかを返す（integrate.BoundReason）。
//   - `tree leftover <ツリー> <名前>`: 親のワークツリーに、承認待ちの提案・作業中の子・MR が残っているかを返す。
//   - `tree base-bound <チェックアウト> <ブランチ>`: 直接作業の取り込み先のブランチが結び付くかを返す
//     （branch.BaseBound）。

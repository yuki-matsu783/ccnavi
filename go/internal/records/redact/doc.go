// Package redact は記録に残す文字列から、秘密の形をした部分を伏せる。
//
// 判定には使わない。止める・通すは伏せる前の文字列で決め、伏せるのは記録（audit）と診断ログ
// （diaglog）に書く文字列だけ。判定の側で伏せると、伏せた形にルールを当てることになる。
// 見つけ方は形だけなので、取りこぼしも、秘密でないものを伏せることもある。`$VAR` のように変数を
// 指すだけの値は伏せない。
//
// Python の re の先読み・後読み・`\b`・Unicode の `\s` `\w` は RE2 に無いので、形ごとに「始まりの
// 候補を探す正規表現」「その位置に固定した全体の正規表現」「前後の字の検査」に分けて、Python の
// finditer と同じ範囲を返す（form）。候補の検査に失敗しても全体の照合を走らせないので、手間は長さに
// ほぼ比例する。
//
// Python からの対応: redact.redact → Redact、mask → Mask、MASK → Stars。

// Package reads は、セッションのコンテキストに乗ったファイルを記録し、チケットの本文に載せる形にする。
//
// PostToolUse ごとに、ツールが読んだ・書いた・結果に出したファイルを `<state>/reads-<セッション>.json` に足す。拾うのは
// Read・Write・Edit・MultiEdit・NotebookEdit の対象、Grep・Glob の結果に出たファイル、Bash のコマンドの引数と標準出力に
// 出たパスである。Bash は字面からの推測（best effort）で、実在するファイルだけを残す。ワークスペースルートの外、`.git`
// の中、ルート直下の logs/、秘密を置く名前（leftOut）は記録しない。メインとサブエージェントは同じセッションの記録に入る。1 つのセッションで複数のチケットを扱えば混ざる。
//
// 形は `{"session", "entries": [{"path", "tools": {<ツール名>: <回数>}, "seen"}]}` である。path は正規化した絶対パス、
// seen は最後に見た時刻（UNIX 秒）。上限は maxEntries 件で、seen の古いものから捨てる。読むときは session が完全に
// 一致する記録だけを使う。Sessions は、あるディレクトリ（チケットのワークツリー）の下を記録しているセッションを引く。
//
// 保存できなくても何も言わない。記録は補助のため。並行して書かれると 1 回ぶん落ちることがあるが、補わない。
package reads

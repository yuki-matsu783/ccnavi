// Package prune は記録と state の後始末。記録を大きさでローテートし、古い記録と終わったセッションの記録を消す。
//
// 走るのはセッションの開始と、ユーザがターミナルから打つ `ccnavi user prune` だけ（hook は呼び出しのたびに
// プロセスを起こすので、重い仕事はセッションに 1 度の場所へ置く）。
//
// 判定の記録（logs/decisions.jsonl）は上限を超えたら `decisions.<日時>.jsonl` へ名前を変え、1 行も破棄しない。
// 消すのはローテートした記録のうち保持日数を過ぎたものだけ。診断ログ（logs/diag/*.log）も同じしきい値で
// ローテートし、保持日数のあいだ書かれていないものを消す。state（logs/state/）はセッションを名前に持つものだけを、
// セッションごとにまとめて消す。そのセッションの記録のどれかが保持日数のうちに書かれていれば全部を残す
// （Claude Code はセッションの終わりを知らせないので、「終わった」は「保持日数のあいだ何も書いていない」で読む）。
// いま始まったセッションは日付を見ずに残す。セッションを名前に持たないもの（レビューの下書き・退避した
// ファイル・自己防衛の実体）は消さない。Stop の AI 判定の記録はそれ自身の日付で、再評価用の材料と試行の
// イベントは別の保持日数（CCNAVI_STOP_REVIEW_KEEP_DAYS）で消す。state の `idle/`（放置したセッションの引き継ぎ）は
// ここでは消さず、handoff.Prune が 7 日で消す。
//
// しきい値は環境変数で動かせる。0 はその段を止める。読めない値・有限でない値・0 より大きく下限より小さい値は
// 既定で動き、報告に出す（下限が無いと、しきい値を 0 に近づけるだけで保持日数のうちの記録が消える）。
// 置き場への道にリンクがあれば辿らずに報告する（リンクの先は ccnavi の置き場とは限らない）。
//
// Python からの対応: run → Run（now・dry_run は Options）、summary → Summary、lines → Lines、
// Report の rotated → rotated（From・To）、kept_ops → KeptOps。
